OLD_NOTICE_IDS = [_id('qmah-ops-notice', n) for n in range(11)] + [_id(f'qmah-notice-v2-{k}', n) for k in 'cs' for n in range(30)]


def lit(s):
    return "N'" + s.replace("'", "''") + "'"


def main(root, out_path):
    pick = {}
    for cat in sorted(os.listdir(root)):
        items = sorted(i for i in os.listdir(os.path.join(root, cat)) if os.path.exists(os.path.join(root, cat, i, 'display.jpg')))
        pick[cat] = [(i, os.path.getsize(os.path.join(root, cat, i, 'display.jpg'))) for i in items[8:20]] or [(i, 0) for i in items[:3]]

    def media_sql(pid, cats, n):
        rows = []
        for k, cat in enumerate(cats):
            item, size = pick[cat][(n + k) % len(pick[cat])]
            rows.append(
                "INSERT INTO social.MediaAssets (Id,SequenceNo,OwnerUserId,PostId,OriginalFileName,StoredPath,ContentType,FileSize,AltText,Status,CreatedAt,UpdatedAt,AiReviewedAt) "
                f"SELECT NEWID(),(SELECT ISNULL(MAX(SequenceNo),0)+1 FROM social.MediaAssets),p.UserId,p.Id,N'display.jpg',N'/media/catalog/{cat}/{item}/display.jpg','image/jpeg',{size},N'圖鑑文物照片','ACTIVE',p.CreatedAt,p.CreatedAt,p.CreatedAt "
                f"FROM social.SocialPosts p WHERE p.Id='{pid}' AND NOT EXISTS (SELECT 1 FROM social.MediaAssets m WHERE m.PostId=p.Id AND m.StoredPath=N'/media/catalog/{cat}/{item}/display.jpg');")
        return rows

    out = ['SET XACT_ABORT ON;', 'BEGIN TRANSACTION;',
           "DECLARE @admin uniqueidentifier = (SELECT Id FROM [user].AspNetUsers WHERE Email='admin@qmah.local');"]
    ids = ','.join(f"'{i}'" for i in OLD_NOTICE_IDS)
    # 舊版公告與依金額逐檔的點數兌換公告（只留一篇總覽）
    out.append("CREATE TABLE #old (Id uniqueidentifier PRIMARY KEY);")
    out.append(f"INSERT INTO #old SELECT Id FROM social.SocialPosts WHERE Id IN ({ids});")
    out.append("INSERT INTO #old SELECT Id FROM social.SocialPosts WHERE PostType='ANNOUNCEMENT' AND BoardCode='STORE' "
               "AND (Title LIKE N'鑑定點數兌換%' OR Title LIKE N'商城優惠活動｜鑑定點數兌換%' OR Title LIKE N'%點數兌換%折價券：%') AND Id NOT IN (SELECT Id FROM #old);")
    # 早期展示用的零碎提示公告（社群看板），一律換成上面的正式公告
    keep = ','.join(f"'{_id('qmah-notice-v3-c', n)}'" for n in range(len(COMMUNITY)))
    out.append("INSERT INTO #old SELECT Id FROM social.SocialPosts WHERE PostType='ANNOUNCEMENT' AND BoardCode IN ('GENERAL','GUIDE') "
               f"AND Id NOT IN ({keep}) AND Id NOT IN (SELECT Id FROM #old);")
    out.append("DELETE FROM social.PostBookmarks WHERE PostId IN (SELECT Id FROM #old);")
    out.append("DELETE FROM social.SocialComments WHERE PostId IN (SELECT Id FROM #old);")
    out.append("DELETE FROM social.MediaAssets WHERE PostId IN (SELECT Id FROM #old);")
    out.append("DELETE FROM social.SocialPosts WHERE Id IN (SELECT Id FROM #old);")
    out.append("DROP TABLE #old;")

    def insert_post(key, n, when, board, title, body):
        assert ';' not in title + body and '；' not in title + body, title
        pid = _id(f'qmah-notice-v3-{key}', n)
        ts = f"CAST('{when}' AS datetime2(3))"
        out.append(f"IF NOT EXISTS (SELECT 1 FROM social.SocialPosts WHERE Id='{pid}') "
                   f"INSERT INTO social.SocialPosts (Id,BoardCode,UserId,PostType,PublisherType,ContentMode,Title,Content,Status,CreatedAt,UpdatedAt,AiReviewedAt,MediaLayout) "
                   f"VALUES ('{pid}','{board}',@admin,'ANNOUNCEMENT','OFFICIAL','TEMPLATE',{lit(title)},{lit(body)},'PUBLISHED',{ts},{ts},{ts},'SECONDARY');")
        out.append(f"UPDATE social.SocialPosts SET Title={lit(title)},Content={lit(body)} WHERE Id='{pid}';")
        return pid

    for n, (when, board, title, body, cats) in enumerate(COMMUNITY):
        out += media_sql(insert_post('c', n, when, board, title, body), cats, n)
    for n, (when, title, body, cats) in enumerate(STORE_NOTICES):
        out += media_sql(insert_post('s', n, when, 'STORE', title, body), cats, n + 3)
    for n, (when, title, body) in enumerate(STORE_CAMPAIGNS):
        out += media_sql(insert_post('k', n, when, 'STORE', title, body), ['enamel', 'jade', 'coin', 'bronze', 'lacquer', 'ceramic'][n:n + 1], n + 5)

    # 既有優惠券公告：用舊標題或新標題找到貼文並改寫（保留 Id 與發文日期）
    for old, new, body in STORE:
        assert ';' not in new + body and '；' not in new + body, new
        out.append(f"UPDATE social.SocialPosts SET Title={lit(new)},Content={lit(body)} WHERE PostType='ANNOUNCEMENT' AND BoardCode='STORE' "
                   f"AND (Title=N'商城優惠活動｜{old}' OR Title={lit(new)} OR Title={lit(LEGACY.get(old, new))});")
    # 發文日回到各檔活動開始之前
    for prefix, when in [('同好回饋券', '2026-08-28 10:00:00'), ('新會員圖鑑禮', '2026-08-10 10:00:00'), ('冬季預約優惠', '2026-10-05 10:00:00'),
                         ('鑑定遊戲獎勵', '2026-08-20 10:00:00'), ('秋日收藏優惠', '2026-09-06 10:00:00'), ('修復主題優惠', '2026-09-14 10:00:00')]:
        out.append(f"UPDATE social.SocialPosts SET CreatedAt='{when}',UpdatedAt='{when}' WHERE BoardCode='STORE' AND PostType='ANNOUNCEMENT' AND Title LIKE N'{prefix}%';")
    out.append('COMMIT;')
    open(out_path, 'w', encoding='utf-8-sig').write('\n'.join(out) + '\n')
    print('OK', len(COMMUNITY), 'community +', len(STORE_NOTICES), 'store notices +', len(STORE_CAMPAIGNS), 'campaigns +', len(STORE), 'coupon posts ->', out_path)


